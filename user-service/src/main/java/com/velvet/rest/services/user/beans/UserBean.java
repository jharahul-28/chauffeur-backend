package com.velvet.rest.services.user.beans;

import java.io.Serializable;

import javax.validation.constraints.NotEmpty;
import javax.validation.constraints.NotNull;
import javax.validation.constraints.Null;

import com.velvet.rest.services.user.constants.UserConstants.Gender;

import io.swagger.annotations.ApiModel;
import io.swagger.annotations.ApiModelProperty;
import lombok.Data;

/**
 * Bean to be returned with Contains Application Level Auth User
 *
 * @author Mohit
 * @version $Id: $Id
 */
@Data
@ApiModel(description = "User Request ")
public class UserBean implements Serializable {

	private static final long serialVersionUID = 2102504245219017738L;

	@ApiModelProperty(value = " Autogenerated Database Id.", readOnly = true)
	@Null
	private Long id;

	private String countryCode;

	@ApiModelProperty(value = "Phone no. of user", allowEmptyValue = false, required = true)
	@NotEmpty
	private String phone;

	@ApiModelProperty(value = "Email of user", allowEmptyValue = false, required = true)
	@NotEmpty
	private String email;

	@ApiModelProperty(value = "Gender of user", allowEmptyValue = false, required = true)
	@NotNull
	private Gender gender;

	@ApiModelProperty(value = "Whether the user is blocked", readOnly = true)
	private Boolean blocked;

	public static UserBean newInstance() {
		return new UserBean();
	}
}
